import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import ts from 'typescript';
import {projectScope} from '../lib/native-project-scope.mjs';
import {createProjectContext} from '../lib/native-project-context.mjs';
import {selectProjectCheck, checkObservation} from '../lib/native-project-checks.mjs';
import {createProjectFeedback, componentFlags, componentInstructions} from '../lib/native-project-feedback.mjs';

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'native-project-feedback-'));
const rules = [{permission: 'read', pattern: '*', action: 'allow'}];
const put = (name, text) => { fs.mkdirSync(path.dirname(path.join(root, name)), {recursive: true}); fs.writeFileSync(path.join(root, name), text); };
const run = (command, args = []) => spawnSync(command, args, {cwd: root, encoding: 'utf8'});
const observe = plan => {
  const result = spawnSync(plan.command, {cwd: path.join(root, plan.workdir), shell: true, encoding: 'utf8'});
  return checkObservation(plan, result.stdout + result.stderr, {exit: result.status}, 0);
};
try {
  assert.equal(run('git', ['init', '-q']).status, 0);
  put('package.json', JSON.stringify({type: 'module', main: './src/index.ts', scripts: {test: 'node --test', typecheck: 'tsc --noEmit'}}));
  put('tsconfig.json', JSON.stringify({compilerOptions: {paths: {'@src/*': ['./src/*']}, module: 'nodenext'}}));
  put('src/value.ts', 'export const value = 1;\nexport const legacy = () => 7;\n');
  put('src/barrel.ts', "export {value as publicValue, legacy} from '@src/value';\n");
  put('src/index.ts', "export {publicValue, legacy} from './barrel.js';\n");
  put('tests/consumer.test.ts', "import {publicValue} from '../src/index.js';\nexport const result = publicValue;\n");
  put('src/unrelated.ts', 'export const nope = 0;\n');
  put('src/queue.ts', 'export class Queue { onIdle(): Promise<void> {return Promise.resolve();} }\n');
  put('src/dynamic.ts', "export const load = () => import('./value.js');\n");
  const analyze = createProjectContext(ts);
  const first = analyze(projectScope(root, rules), 'src/value.ts');
  assert.ok(first.exports.items.some(e => e.file === 'src/index.ts' && e.name === 'publicValue'), JSON.stringify(first));
  assert.ok(first.chains.items.some(e => e.files.join('/') === 'src/value.ts/src/barrel.ts/src/index.ts/tests/consumer.test.ts'));
  assert.ok(first.tests.items.some(e => e.file === 'tests/consumer.test.ts'));
  assert.ok(first.entryPoints.items.some(e => e.file === 'src/index.ts'));
  assert.ok(first.references.items.every(e => Number.isInteger(e.line) && e.method === 'typescript-symbol-reference'));
  assert.ok(!first.importers.items.some(e => e.file === 'src/unrelated.ts'));
  assert.equal(first.importers.items.some(e => e.file === 'src/dynamic.ts'), false);
  assert.ok(first.limits.some(s => s.includes('dynamic imports')));
  const dynamic = analyze(projectScope(root, rules), 'src/dynamic.ts');
  assert.equal(dynamic.dynamic.items[0].confidence, 'unresolved');
  const symbol = analyze(projectScope(root, rules), 'value');
  assert.equal(symbol.definitions.items[0].file, 'src/value.ts');
  assert.equal(analyze(projectScope(root, rules), 'doesNotExist').definitions.total, 0);
  assert.equal(analyze(projectScope(root, rules), 'onIdle').definitions.items[0].file, 'src/queue.ts');
  put('src/barrel.ts', "export {legacy} from '@src/value';\n");
  const refreshed = analyze(projectScope(root, rules), 'value');
  assert.notEqual(first.snapshot, refreshed.snapshot);
  assert.equal(refreshed.cost.reparsedFiles, 1);
  assert.ok(!refreshed.exports.items.some(e => e.file === 'src/barrel.ts' && e.name === 'publicValue'));
  assert.ok(analyze(projectScope(root, rules), 'src/value.ts', {limit: 1}).references.truncated);
  const bounded = analyze(projectScope(root, rules, {maxFiles: 2}), 'value');
  assert.ok(bounded.limits.some(s => s.includes('omitted')));
  put('src/private.ts', 'export const forbidden = 8;\n');
  const denied = projectScope(root, [...rules, {permission: 'read', pattern: '*private.ts', action: 'deny'}]);
  assert.equal(denied.files.has('src/private.ts'), false);
  assert.throws(() => projectScope(root, rules).relative('../outside'), /outside/);
  fs.symlinkSync('/etc/passwd', path.join(root, 'secret.ts'));
  assert.equal(projectScope(root, rules).files.has('secret.ts'), false);

  // Ordinary runnable Node project: a real export defect, repair, and an
  // intentional contract change. No harness paths in project checks.
  fs.rmSync(path.join(root, 'tests'), {recursive: true});
  put('value.mjs', 'export const value = 1; export const legacy = () => 7;\n');
  put('index.mjs', "export {value, legacy} from './value.mjs';\n");
  put('consumer.test.mjs', "import {value,legacy} from './index.mjs'; import {test} from 'node:test'; import assert from 'node:assert/strict'; test('consumer',()=>{assert.equal(value,1);assert.equal(legacy(),7)});\n");
  let plan = selectProjectCheck(projectScope(root, rules), 'harness-check value.mjs');
  assert.equal(plan.command, 'npm run test');
  assert.equal(observe(plan).status, 'passed');
  put('index.mjs', "export {legacy} from './value.mjs';\n");
  const failure = observe(selectProjectCheck(projectScope(root, rules), 'harness-check value.mjs'));
  assert.equal(failure.exit, 1); assert.match(failure.diagnostics, /does not provide an export named 'value'/);
  put('index.mjs', "export {value, legacy} from './value.mjs';\n");
  assert.equal(observe(selectProjectCheck(projectScope(root, rules), 'harness-check value.mjs')).status, 'passed');
  put('value.mjs', 'export const value = 2; export const legacy = () => 7;\n');
  const oldFailure = observe(selectProjectCheck(projectScope(root, rules), 'harness-check value.mjs'));
  assert.equal(oldFailure.exit, 1);
  put('consumer.test.mjs', fs.readFileSync(path.join(root, 'consumer.test.mjs'), 'utf8').replace('value,1', 'value,2'));
  assert.equal(observe(selectProjectCheck(projectScope(root, rules), 'harness-check value.mjs')).status, 'passed');
  plan = selectProjectCheck(projectScope(root, rules), 'harness-check consumer.test.mjs');
  assert.equal(plan.completeSelection, false); assert.match(plan.command, /^node --test /);
  assert.equal(observe(plan).status, 'passed');
  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json')));
  pkg.scripts.typecheck = 'nonexistent-feedback-tool'; put('package.json', JSON.stringify(pkg));
  const environment = observe(selectProjectCheck(projectScope(root, rules), 'harness-check value.mjs typecheck'));
  assert.equal(environment.status, 'environment-or-resolution-error');
  assert.equal(selectProjectCheck(projectScope(root, rules), 'harness-check .').available.some(p => p.name === 'typecheck'), true);

  const saved = new Map(); let compilerLoads = 0;
  const feedback = flags => createProjectFeedback({directory: root, rules, flags, save: (n,v) => saved.set(n, structuredClone(v)), checkActive: () => {}, loadCompiler: async () => { compilerLoads++; return ts; }});
  const invoke = async (f, tool, args, snapshot) => {
    const input = {tool, args, callID: Math.random().toString()}, output = {args: {...args}, output: 'native-result', metadata: {exit: 0}};
    const componentCheck = f.before(input, output, snapshot);
    input.args = output.args;
    if (componentCheck) { const r = spawnSync(output.args.command, {shell: true, cwd: path.join(root, output.args.workdir), encoding: 'utf8'}); output.output = r.stdout + r.stderr; output.metadata.exit = r.status; }
    await f.after(input, output, {componentCheck}, snapshot);
    return output;
  };
  const off = feedback({A:false,B:false});
  assert.equal((await invoke(off,'read',{filePath:'value.mjs'},'one')).output,'native-result');
  assert.equal(saved.size,0); assert.equal(compilerLoads,0);
  assert.equal(componentInstructions({A:false,B:false}),'');
  assert.deepEqual(componentFlags({}),{A:false,B:false});
  assert.throws(()=>componentFlags({HARNESS_TASK_CHECKS:'yes'}),/0 or 1/);
  const b = feedback({A:false,B:true});
  const b1 = await invoke(b,'bash',{command:'harness-check value.mjs',workdir:'.'},'one');
  assert.match(b1.output,/Project check B/); assert.equal(compilerLoads,0); assert.ok(!b1.output.includes('Computed code context'));
  const b2 = await invoke(b,'bash',{command:'harness-check value.mjs',workdir:'.'},'one');
  assert.match(b2.output,/not-rerun/);
  const a = feedback({A:true,B:false});
  assert.match((await invoke(a,'read',{filePath:'value.mjs'},'one')).output,/Computed code context A/);
  put('value.mjs','export const value = 3; export const legacy = () => 7;\n');
  await invoke(a,'edit',{},'two');
  assert.equal(saved.get('component-context.json')[0].stale,true);
  assert.match((await invoke(a,'read',{filePath:'value.mjs'},'two')).output,/Computed code context A/);
  assert.equal(saved.get('component-context.json')[0].stale,false);
  console.log(JSON.stringify({status:'passed',compiler:ts.version,realModelRequests:0,checks:['alias-re-export-symbol','entry-consumer-test-chain','incremental-freshness','dynamic-and-truncation','permission-and-symlink','real-fail-repair','intentional-contract-change','environment','independent-switches','native-bash-adapter','historical-deduplication']}));
} finally { fs.rmSync(root,{recursive:true,force:true}); }
